/** 5×7 number-box characters (keys 1–9, A–C). */
const NUMBERS = {
  '1': ['..#..', '.##..', '..#..', '..#..', '..#..', '..#..', '.###.'],
  '2': ['.###.', '#...#', '....#', '...#.', '..#..', '.#...', '#####'],
  '3': ['.###.', '#...#', '....#', '..##.', '....#', '#...#', '.###.'],
  '4': ['...#.', '..##.', '.#.#.', '.#.#.', '#..#.', '#####', '...#.'],
  '5': ['#####', '#....', '####.', '....#', '....#', '#...#', '.###.'],
  '6': ['..##.', '.#...', '#....', '####.', '#...#', '#...#', '.###.'],
  '7': ['#####', '#...#', '...#.', '...#.', '..#..', '..#..', '..#..'],
  '8': ['.###.', '#...#', '#...#', '.###.', '#...#', '#...#', '.###.'],
  '9': ['.###.', '#...#', '#...#', '.####', '....#', '...#.', '.##..'],
  A: ['..#..', '.#.#.', '#...#', '#...#', '#####', '#...#', '#...#'],
  B: ['####.', '#...#', '#...#', '####.', '#...#', '#...#', '####.'],
  C: ['.###.', '#...#', '#....', '#....', '#....', '#...#', '.###.'],
};

const W = 47;
const H = 23;
const on = (rows, x, y) => rows[y]?.[x] === '#';
const inBox = (x, y) => y >= 12 && y <= 21 && x >= 38 && x <= 46 && !(y === 12 && x === 38);
const inBlock = (x, y) => y <= 21 && x <= 45 && !((y === 0 || y === 21) && x === 0) && !(y === 0 && x === 45);

/** Ink at (x, y) of icon `index` labelled with key `key`. */
function pixel(index, key, selected, x, y) {
  const glyph = GLYPHS[index];
  const digit = on(NUMBERS[key], x - 40, y - 14);
  if (inBox(x, y)) return selected ? digit : !digit;
  if (selected) return inBlock(x, y) && !on(glyph, x, y);
  return (x < 46 && y < 22 && on(glyph, x, y)) || (x === 46 && y >= 1 && y <= 21) || (y === 22 && x >= 1 && x <= 45);
}

/** The icon's pixels as rows of '#' and '.'. */
export function iconRows(index, key, selected) {
  return Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) => (pixel(index, key, selected, x, y) ? '#' : '.')).join(''));
}

/** The icon as an SVG of LCD pixels (1 unit = 1 pixel), drawn in currentColor. */
export function menuIcon(index, key, selected) {
  let d = '';
  iconRows(index, key, selected).forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  const ns = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(ns, 'svg');
  svg.setAttribute('viewBox', `0 0 ${W} ${H}`);
  svg.setAttribute('shape-rendering', 'crispEdges');
  const path = document.createElementNS(ns, 'path');
  path.setAttribute('d', d);
  path.setAttribute('fill', 'currentColor');
  svg.append(path);
  return svg;
}
